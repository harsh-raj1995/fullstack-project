// Activity heatmap generator for the past 24 weeks (7 rows x 24 cols)
export const generateHeatmapData = () => {
  const days = [];
  const today = new Date();
  
  for (let i = 168; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split("T")[0];
    
    // Deterministic pseudo-random generation based on date hash
    const dayOfWeek = d.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;
    const seed = (d.getDate() * 13 + d.getMonth() * 31 + d.getFullYear()) % 100;
    
    let count = 0;
    if (seed > 85) count = Math.floor(seed % 6) + 4; // high activity
    else if (seed > 40) count = Math.floor(seed % 4) + 1; // moderate activity
    else if (seed > 20 && !isWeekend) count = Math.floor(seed % 3) + 1;
    else count = 0; // rest day

    let level = 0;
    if (count >= 7) level = 4;
    else if (count >= 5) level = 3;
    else if (count >= 3) level = 2;
    else if (count >= 1) level = 1;

    days.push({
      date: dateStr,
      count,
      level,
      dayOfWeek,
    });
  }
  return days;
};
